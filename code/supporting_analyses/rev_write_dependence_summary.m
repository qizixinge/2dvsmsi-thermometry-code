% Collect the pseudo-replica SNR that statistics_analysis_final.m needs into one
% derived file in data/: noise_dependence_summary.mat.
% Run after rev_pseudoreplica_analysis.m.
% The committed noise_dependence_summary.mat was written by an earlier version of
% this script and holds additional fields; the TBME pipeline reads only
% snr_replica and n_replicas.
here = fileparts(mfilename('fullpath')); root = fileparts(here);
addpath(root); project = project_paths();
outdir = getenv('VSMSI_REV_DIR'); if isempty(outdir), outdir = project.supporting; end
summary_file = fullfile(outdir,'pseudoreplica_summary.mat');
if ~isfile(summary_file)
    error('rev:MissingSummary', ['%s not found. Run code/supporting_analyses/rev_pseudoreplica.m and ' ...
        'rev_pseudoreplica_analysis.m with the same VSMSI_REV_DIR first.'], summary_file);
end
A = load(summary_file,'OUT');
OUT = A.OUT;
snr_replica = [OUT(1).snr(1) OUT(2).snr(1) OUT(1).snr(2) OUT(2).snr(2)];   % PFA-SOS Full-SOS PFA-MIP Full-MIP
n_replicas = [OUT(1).NR OUT(2).NR];
tp = OUT(1).tp;  assert(OUT(2).tp == tp,'rev:Tp','PFA and Full replicas are from different time points. Fix: rerun rev_pseudoreplica_analysis.m.');
source = sprintf('snr_replica: pseudo-replica simulation at time point %d (code/supporting_analyses/rev_pseudoreplica*.m)', tp);
save(fullfile(project.data,'noise_dependence_summary.mat'),'snr_replica','n_replicas','source','tp');
% LaTeX macros (SNR as an integer, replica counts)
f_ = fullfile(project.results,'numbers_snr.tex');
fid = fopen(f_,'w');
for tries = 1:5, if fid > 0, break; end, pause(1); fid = fopen(f_,'w'); end
assert(fid > 0,'rev:Fopen','Cannot open numbers_snr.tex. Fix: close the file or wait for the sync client.');
fprintf(fid,'%% GENERATED by code/supporting_analyses/rev_write_dependence_summary.m; do not edit.\n');
nm = {'PfaSos','FullSos','PfaMip','FullMip'};
for q = 1:4, fprintf(fid,'\\newcommand{\\nSnr%s}{%.0f}\n', nm{q}, snr_replica(q)); end
fprintf(fid,'\\newcommand{\\nReplicasPfa}{%d}\n\\newcommand{\\nReplicasFull}{%d}\n', n_replicas);
fprintf(fid,'\\newcommand{\\nSnrTp}{%d}\n', tp);
fclose(fid);
fprintf('wrote noise_dependence_summary.mat\nsnr_replica = %s; replicas %s\n', mat2str(snr_replica,4), mat2str(n_replicas));
