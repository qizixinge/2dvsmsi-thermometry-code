% Purpose: sensitivity of the GRE/PRF calibration to time point 2, whose GRE phase image departs from the cooling trend (see rev_gre_timepoint_residual.m).
% Repeats the per-ROI PRF calibration and the leave-one-time-point-out
% cross-validation of statistics_analysis_final.m with time points 1-9 (primary
% analysis) and without time point 2 (1,3-9).  Prints coefficients and LOOCV RMSE,
% writes gre_calibration_sensitivity.mat to VSMSI_REV_DIR (or ./out) and the macros
% to output/results/numbers_gre_sensitivity.tex.
here = fileparts(mfilename('fullpath')); root = fileparts(here);
addpath(root); addpath(here);
project = project_paths();
outdir = getenv('VSMSI_REV_DIR'); if isempty(outdir), outdir = project.supporting; end
if ~isfolder(outdir), mkdir(outdir); end

R = load(fullfile(project.data,'ROI_and_tempr_resolved.mat'));
G = load(fullfile(project.data,'phaseMAPr_and_magmap.mat'),'phaseMAPr');
sets = {1:9, [1 3:9]};
alpha = zeros(numel(sets),4);  rmse = zeros(numel(sets),4);
for s = 1:numel(sets)
    tp  = sets{s};  n = numel(tp);
    roi = cellfun(@(r) r(tp,:), R.ROI_PRF_128_series, 'UniformOutput', false);
    [MNSp,~,~,~,~,am] = PRFreconnew(G.phaseMAPr(:,:,tp), roi{:}, R.temprp1(tp,:), R.oil1,R.oil2,R.oil3,R.oil4);
    alpha(s,:) = -am;                     % positive, ds per degC
    Y = -MNSp;  X = R.temprp1(tp,:);
    for k = 1:4                           % same LOOCV as statistics_analysis_final.m
        e = zeros(n,1);
        for lo = 1:n
            tr = setdiff(1:n, lo);
            xt = X(tr,k) - mean(X(tr,k));  yt = Y(tr,k) - mean(Y(tr,k));
            bt = sum(xt.*yt)/sum(xt.^2);
            e(lo) = (Y(lo,k) - mean(Y(tr,k)))/bt + mean(X(tr,k)) - X(lo,k);
        end
        rmse(s,k) = sqrt(mean(e.^2));
    end
    fprintf('time points %s: alpha x1e-8 [%s]  remote mean %.3f | LOOCV RMSE degC [%s]\n', mat2str(tp), ...
        sprintf('%.3f ', alpha(s,:)*1e8), mean(alpha(s,[1 4]))*1e8, sprintf('%.2f ', rmse(s,:)));
end
save(fullfile(outdir,'gre_calibration_sensitivity.mat'),'sets','alpha','rmse');
copyfile(fullfile(outdir,'gre_calibration_sensitivity.mat'), fullfile(project.results,'gre_calibration_sensitivity.mat'));
rn = {'I','II','III','IV'};
f_ = fullfile(project.results,'numbers_gre_sensitivity.tex');
fid = fopen(f_,'w');
for tries = 1:5, if fid > 0, break; end, pause(1); fid = fopen(f_,'w'); end
assert(fid > 0,'rev:Fopen','Cannot open numbers_gre_sensitivity.tex. Fix: close the file or wait for the sync client.');
fprintf(fid,'%% GENERATED by code/supporting_analyses/rev_gre_calibration_sensitivity.m; do not edit.\n');
fprintf(fid,'%% GreSens* = GRE calibration without time point 2 (time points 1,3-9); the primary (all nine) values are AlphaGre*/RmseGre* in numbers.tex.\n');
for k = 1:4
    fprintf(fid,'\\newcommand{\\nGreSensAlpha%s}{%.3f}\n', rn{k}, alpha(2,k)*1e8);
    fprintf(fid,'\\newcommand{\\nGreSensRmse%s}{%.2f}\n', rn{k}, rmse(2,k));
end
fprintf(fid,'\\newcommand{\\nGreSensAlphaRemote}{%.3f}\n', mean(alpha(2,[1 4]))*1e8);
fprintf(fid,'\\newcommand{\\nGreSensAlphaRemoteTwo}{%.2f}\n', mean(alpha(2,[1 4]))*1e8);
fprintf(fid,'\\newcommand{\\nGreSensRmseNearMin}{%.2f}\n', min(rmse(2,[2 3])));
fprintf(fid,'\\newcommand{\\nGreSensRmseNearMax}{%.2f}\n', max(rmse(2,[2 3])));
fclose(fid);
