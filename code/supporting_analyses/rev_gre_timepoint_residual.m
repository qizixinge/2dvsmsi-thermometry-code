% Purpose: quantify how far each GRE phase image departs from the cooling trend of the other eight (nine time points), the reason time point 2 is left out of the dT-map display and the Bland-Altman comparison.
% For each time point k, a per-voxel straight line is fitted to the unwrapped,
% oil-drift-corrected phase of the other eight time points and extrapolated to
% k; the residual is converted to temperature with the remote-ROI PRF
% coefficient.  Statistics use the GRE display mask (3x edge-band maximum of
% the GRE magnitude, oil bottles excluded).  Prints one SD per time point and
% writes gre_timepoint_residual.mat to VSMSI_REV_DIR (or ./out) and the macros to
% output/results/numbers_gre_residual.tex.
% The trend is linear in the actual acquisition time (not in the time-point index).
% Second variant (resid_sd_ex2): the trend is fitted without time point 2, to
% check whether the remaining time points (in particular time point 1) are
% consistent with the cooling trend once the outlier no longer contaminates it.
here = fileparts(mfilename('fullpath')); root = fileparts(here);
addpath(root); addpath(here);
project = project_paths();
outdir = getenv('VSMSI_REV_DIR'); if isempty(outdir), outdir = project.supporting; end
if ~isfolder(outdir), mkdir(outdir); end

G = load(fullfile(project.data,'phaseMAPr_and_magmap.mat'),'phaseMAPr','magmap');
R = load(fullfile(project.data,'ROI_and_tempr_resolved.mat'),'oil1','oil2','oil3','oil4','scan_start_s');
X = load(fullfile(project.data,'YX.mat'),'yangaib');
S = load(fullfile(project.results,'statistics_results_final.mat'),'ALPHA_PAPER');

ph  = permute(unwrap(permute(double(G.phaseMAPr),[3 1 2])),[2 3 1]);
num = size(ph,3);
oil = logical(max(cat(3,R.oil1,R.oil2,R.oil3,R.oil4),[],3));
mag = double(G.magmap);  w = 10;
edge = [reshape(mag(1:w,:),[],1); reshape(mag(end-w+1:end,:),[],1); ...
        reshape(mag(:,1:w),[],1); reshape(mag(:,end-w+1:end),[],1)];
mask = mag >= 3*max(edge) & ~logical(X.yangaib);

lam   = gre_params().lam;                  % B0*gamma*dTE (dTE = 2.46 ms), as in prf_maps
alpha = mean(S.ALPHA_PAPER([1 4]));          % remote-ROI coefficient
% actual GRE acquisition times (minutes after the first GRE scan); the nine scans are unevenly spaced (6.2-10.6 min)
t = (R.scan_start_s(:,1) - R.scan_start_s(1,1))/60;
resid_sd = zeros(1,num);  resid_sd_ex2 = nan(1,num);
for v = 1:2
    for k = 1:num
        if v == 1, o = setdiff(1:num,k); else, o = setdiff(1:num,[k 2]); if k == 2, continue; end, end
        A = [ones(numel(o),1) t(o)];
        Y = reshape(ph(:,:,o),[],numel(o))';
        c = A \ Y;
        r = ph(:,:,k) - reshape(c(1,:) + c(2,:)*t(k), size(mask));
        r = r - mean(r(oil));                    % same oil drift reference as the analysis
        dT = -r/lam/alpha;
        if v == 1, resid_sd(k) = std(dT(mask)); else, resid_sd_ex2(k) = std(dT(mask)); end
    end
end
fprintf('GRE residual SD vs cooling trend of the other %d time points (degC, %d voxels):\n', num-1, nnz(mask));
fprintf('  time point %d: %.2f\n', [1:num; resid_sd]);
fprintf('same, trend fitted without time point 2 (time point 2 itself: n/a):\n');
fprintf('  time point %d: %.2f\n', [1:num; resid_sd_ex2]);
save(fullfile(outdir,'gre_timepoint_residual.mat'),'resid_sd','resid_sd_ex2','alpha');
copyfile(fullfile(outdir,'gre_timepoint_residual.mat'), fullfile(project.results,'gre_timepoint_residual.mat'));
% macros: GreResSdTp<Word> (1 decimal), range of the time points other than 2
words = {'One','Two','Three','Four','Five','Six','Seven','Eight','Nine'};
oth = setdiff(1:num,2);
fid = fopen(fullfile(project.results,'numbers_gre_residual.tex'),'w');
for tries = 1:5, if fid > 0, break; end, pause(1); fid = fopen(fullfile(project.results,'numbers_gre_residual.tex'),'w'); end
assert(fid > 0,'rev:Fopen','Cannot open numbers_gre_residual.tex. Fix: close the file or wait for the sync client.');
fprintf(fid,'%% GENERATED by code/supporting_analyses/rev_gre_timepoint_residual.m; do not edit.\n');
for k = 1:num
    fprintf(fid,'\\newcommand{\\nGreResSdTp%s}{%.1f}\n', words{k}, resid_sd(k));
end
fprintf(fid,'\\newcommand{\\nGreResSdOthersMin}{%.1f}\n', min(resid_sd(oth)));
fprintf(fid,'\\newcommand{\\nGreResSdOthersMax}{%.1f}\n', max(resid_sd(oth)));
fprintf(fid,'\\newcommand{\\nGreResSdTpOneExTwo}{%.1f}\n', resid_sd_ex2(1));
fprintf(fid,'\\newcommand{\\nGreResSdExTwoMin}{%.1f}\n', min(resid_sd_ex2(oth)));
fprintf(fid,'\\newcommand{\\nGreResSdExTwoMax}{%.1f}\n', max(resid_sd_ex2(oth)));
fprintf(fid,'\\newcommand{\\nGreResNumVox}{%d}\n', nnz(mask));
fclose(fid);
